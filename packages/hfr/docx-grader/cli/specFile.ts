import { dump, load } from 'js-yaml';
import fs from 'node:fs';
import { Check } from '../checks/kinds';
import { DocxSpec, parseSpec } from '../spec/DocxSpec';

const HEADER = `# docx-spec, generated by @hfr/docx-grader.
# Add to any check:
#   hint: Text shown to students when the check fails
#   docs: /link/to/a/documentation/page
# Re-running the CLI keeps hint and docs of checks with the same id.
`;

export const readSpecFile = (specPath: string): DocxSpec => {
    const { spec, errors } = parseSpec(load(fs.readFileSync(specPath, 'utf-8')));
    if (!spec) {
        throw new Error(`${specPath}: ${errors.join(' ')}`);
    }
    errors.forEach((error) => console.warn(`⚠️ ${specPath}: ${error}`));
    return spec;
};

export const writeSpecFile = (specPath: string, spec: DocxSpec) => {
    fs.writeFileSync(specPath, `${HEADER}${dump(spec, { lineWidth: -1, noRefs: true })}`);
};

/** Keeps the hints and documentation links the teacher added to the previous spec. */
export const mergeWithPreviousSpec = (checks: Check[], previousSpec: DocxSpec | undefined): Check[] => {
    const previousChecks = new Map(previousSpec?.checks.map((check) => [check.id, check]));
    return checks.map((check) => {
        const previous = previousChecks.get(check.id);
        return {
            ...check,
            ...(previous?.hint ? { hint: previous.hint } : {}),
            ...(previous?.docs ? { docs: previous.docs } : {})
        };
    });
};
