import { dump, load } from 'js-yaml';
import fs from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { Check } from '../checks/kinds';
import { DocxSpec, parseSpec } from '../spec/DocxSpec';

const HEADER = `# docx-spec, generated by @hfr/docx-grader.
# Add to any check:
#   hint: Text shown to students when the check fails
#   docs: /link/to/a/documentation/page
# Format checks also take source: style (from a style) or any (also direct formatting),
# and defaultSource at the top sets it for all checks without their own.
# Re-running the CLI keeps defaultSource, and hint, docs and source of checks with the same id.
`;

export const readSpecFile = (specPath: string): DocxSpec => {
    const { spec, errors } = parseSpec(load(fs.readFileSync(specPath, 'utf-8')));
    if (!spec) {
        throw new Error(`${specPath}: ${errors.join(' ')}`);
    }
    errors.forEach((error) => console.warn(`⚠️ ${specPath}: ${error}`));
    return spec;
};

/** Formatted with the repository's Prettier config, so `yarn format:check` accepts the spec. */
export const writeSpecFile = async (specPath: string, spec: DocxSpec) => {
    const yaml = `${HEADER}${dump(spec, { lineWidth: -1, noRefs: true })}`;
    const config = await resolveConfig(specPath);
    fs.writeFileSync(specPath, await format(yaml, { ...config, parser: 'yaml' }));
};

/** Hints of checks the document no longer produces, e.g. after its formatting changed, are dropped. */
export const warnAboutDroppedHints = (checks: Check[], previousSpec: DocxSpec | undefined) => {
    const ids = new Set(checks.map((check) => check.id));
    previousSpec?.checks
        .filter((check) => (check.hint || check.docs) && !ids.has(check.id))
        .forEach((check) => console.warn(`⚠️ «${check.id}» gibt es nicht mehr, hint und docs entfallen.`));
};

/** Keeps the hints and documentation links the teacher added to the previous spec. */
export const mergeWithPreviousSpec = (checks: Check[], previousSpec: DocxSpec | undefined): Check[] => {
    const previousChecks = new Map(previousSpec?.checks.map((check) => [check.id, check]));
    return checks.map((check) => {
        const previous = previousChecks.get(check.id);
        return {
            ...check,
            ...(previous?.hint ? { hint: previous.hint } : {}),
            ...(previous?.docs ? { docs: previous.docs } : {}),
            ...(previous && 'source' in previous && previous.source ? { source: previous.source } : {})
        };
    });
};
